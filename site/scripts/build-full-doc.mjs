#!/usr/bin/env node
// <lang>/00-full.md (全文一括版) のジェネレーター。
//
// 各言語ディレクトリの README + 7 分類の全ページを 1 つの Markdown に連結する。
//   - README は「Entry points by goal」の手前まで (サイト向けナビは含めない)
//   - カテゴリindex は「## <分類名>」、各ページは「## <ページH1>」の節になる
//   - ページ内見出しは 1 段下げ (## → ###)
//   - 相対リンクは言語ルート (00-full.md の場所) から正しく解けるよう書き換え
//   - コードフェンス内は一切触らない
//
// 使い方:  node site/scripts/build-full-doc.mjs          (全言語)
//          node site/scripts/build-full-doc.mjs en ja    (指定言語のみ)
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { LOCALES } from '../lib/langs.mjs'

const siteRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const repoRoot = path.resolve(siteRoot, '..')

const args = process.argv.slice(2)
const langs = args.length
  ? args
  : LOCALES.map(l => l.code)

const HEADER = `<!-- Auto-generated by site/scripts/build-full-doc.mjs — do not edit this file directly.
     Edit the individual pages under <lang>/ and regenerate with:
     node site/scripts/build-full-doc.mjs -->`

// ページ相対リンク -> 言語ルート相対 (00-full.md からの相対) への書き換え
function rewriteLinksForRoot(src, pageDir) {
  // pageDir: 言語ルートからのページのディレクトリ ('' / 'api/' など)
  const resolve = target => {
    const joined = path.posix.normalize(path.posix.join(pageDir === '' ? '.' : pageDir, target))
    if (joined === '.') return ''
    return joined
  }
  return src
    // .md リンク
    .replace(/\]\(([^()\s]+\.md)(#[^\s()]*)?\)/g, (full, file, anchor = '') => {
      if (/^(https?:)?\/\//i.test(file) || file.startsWith('/')) return full
      const resolved = resolve(file)
      if (resolved === 'README.md' || resolved === '') return `](README.md${anchor})`
      return `](${resolved}${anchor})`
    })
    // ディレクトリリンク (../history/ 等)
    .replace(/\]\(([^()\s]*\/?\/)(#[^\s()]*)?\)/g, (full, dir, anchor = '') => {
      if (/^(https?:)?\/\//i.test(dir) || dir.startsWith('/')) return full
      const resolved = resolve(dir).replace(/\/$/, '')
      if (resolved === '') return `](README.md${anchor})`
      return `](${resolved}/${anchor})`
    })
}

// 見出しを 1 段下げ (コードフェンス内はそのまま)
function demoteHeadings(src) {
  const lines = src.split('\n')
  let inFence = false
  return lines
    .map(line => {
      if (/^\s*(```|~~~)/.test(line)) {
        inFence = !inFence
        return line
      }
      if (!inFence && /^#{1,5}\s/.test(line)) return '#' + line
      return line
    })
    .join('\n')
}

function stripH1(src) {
  const m = src.match(/^#\s+[^\n]+\n/)
  if (!m) return { body: src, title: null }
  let rest = src.slice(m[0].length)
  rest = rest.replace(/^\n+/, '', 1) // H1直後の空行は1つに
  return { body: '\n' + rest.replace(/^\n+/, ''), title: m[0].replace(/^#\s+/, '').trim() }
}

const CATS = ['getting-started', 'api', 'guides', 'recipes', 'troubleshooting', 'internals', 'history']

for (const code of langs) {
  const langDir = path.join(repoRoot, code)
  if (!fs.existsSync(langDir)) continue
  const topMeta = JSON.parse(fs.readFileSync(path.join(langDir, '_meta.json'), 'utf8'))

  const parts = [HEADER, '']

  // --- README (サイト向けナビの手前まで) ---
  const readme = fs.readFileSync(path.join(langDir, 'README.md'), 'utf8')
  const cut = readme.indexOf('## ')
  const readmeHead = cut > 0 ? readme.slice(0, cut).trimEnd() : readme.trimEnd()
  parts.push(readmeHead)

  for (const cat of CATS) {
    const catDir = path.join(langDir, cat)
    if (!fs.existsSync(catDir)) continue
    const catTitle = topMeta[cat] || cat

    // --- カテゴリ index ---
    const indexPath = path.join(catDir, 'index.md')
    if (fs.existsSync(indexPath)) {
      const { body } = stripH1(fs.readFileSync(indexPath, 'utf8'))
      parts.push('\n---\n', `## ${catTitle}`, demoteHeadings(rewriteLinksForRoot(body.replace(/^\n+/, ''), `${cat}/`)))
    }

    // --- 各ページ (_meta.json の順) ---
    const metaPath = path.join(catDir, '_meta.json')
    let order = null
    if (fs.existsSync(metaPath)) {
      order = Object.keys(JSON.parse(fs.readFileSync(metaPath, 'utf8')))
    }
    const files = fs.readdirSync(catDir).filter(f => f.endsWith('.md') && f !== 'index.md' && f !== '_meta.json')
    files.sort((a, b) => {
      const ka = a.replace(/\.md$/, ''), kb = b.replace(/\.md$/, '')
      const ia = order ? order.indexOf(ka) : -1, ib = order ? order.indexOf(kb) : -1
      if (ia >= 0 && ib >= 0) return ia - ib
      if (ia >= 0) return -1
      if (ib >= 0) return 1
      return a < b ? -1 : a > b ? 1 : 0
    })
    for (const f of files) {
      const { title, body } = stripH1(fs.readFileSync(path.join(catDir, f), 'utf8'))
      parts.push('\n---\n', `## ${title || f.replace(/\.md$/, '')}`, demoteHeadings(rewriteLinksForRoot(body.replace(/^\n+/, ''), `${cat}/`)))
    }
  }

  const out = parts.join('\n').replace(/\n{4,}/g, '\n\n\n') + '\n'
  fs.writeFileSync(path.join(langDir, '00-full.md'), out)
  console.log(`build-full-doc: ${code}/00-full.md (${out.length} bytes)`)
}
